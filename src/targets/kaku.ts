/**
 * Kaku (and WezTerm) color schemes.
 *
 * Two formats come out of the same palette:
 *
 * - Lua tables in `dist/kaku/*.lua`, which Kaku reads from
 *   `config.color_schemes` and WezTerm loads with `config.color_schemes`.
 * - WezTerm-compatible TOML in `dist/kaku/*.toml`, which Kaku lists from its
 *   `<config-dir>/colors/` directory (Settings → Theme).
 */

import { parseHex } from '../color.ts';
import { flavors, flavorName } from '../palette/index.ts';
import type { Flavor } from '../palette/types.ts';
import { kakuFileName, kakuSchemeName, kakuTomlFileName } from './naming.ts';
import type { GeneratedFile } from './vscode.ts';

function quote(value: string): string {
  return `'${value}'`;
}

function hexList(colors: readonly string[]): string {
  return colors.map((hex) => `    ${quote(hex)},`).join('\n');
}

function tomlString(value: string): string {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

function tomlArray(colors: readonly string[]): string {
  return `[\n${colors.map((hex) => `  ${tomlString(hex)}`).join(',\n')}\n]`;
}

/** WezTerm/Kaku color values use rgba(), not #RRGGBBAA. */
function rgba(hex: string, a: number): string {
  const { r, g, b } = parseHex(hex);
  return `rgba(${r},${g},${b},${a.toFixed(2)})`;
}

export function buildKakuScheme(flavor: Flavor): string {
  const f = flavor;
  const s = f.surface;
  const t = f.text;
  const y = f.syntax;
  const dark = f.meta.appearance === 'dark';
  const tabFg = t.secondary;
  const tabActiveBg = s.active;
  const hoverBg = s.overlay;
  const zh = flavorName(f, 'zh');
  const en = flavorName(f, 'en');

  return `-- 墨观 Inkstone · ${zh} · ${en}
-- ${f.meta.description.en}
-- Generated by \`pnpm build\` — do not edit by hand.
--
-- Install: copy this file to ~/.config/kaku/ (or ~/.config/wezterm/),
-- then add the following to your config:
--
--   config.color_schemes = config.color_schemes or {}
--   config.color_schemes['${kakuSchemeName(f)}'] =
--     dofile(wezterm.config_dir .. '/inkstone-${f.meta.id}.lua')
--   config.color_scheme = '${kakuSchemeName(f)}'

return {
  foreground = ${quote(t.primary)},
  background = ${quote(s.base)},

  cursor_bg = ${quote(t.cursor)},
  cursor_fg = ${quote(s.base)},
  cursor_border = ${quote(t.cursor)},

  selection_bg = ${quote(s.selection)},
  selection_fg = ${quote(t.primary)},

  compose_cursor = ${quote(y.number)},
  scrollbar_thumb = ${quote(rgba(t.primary, dark ? 0.18 : 0.22))},
  split = ${quote(s.overlay)},
  visual_bell = ${quote(y.number)},

  ansi = {
${hexList(f.ansi.slice(0, 8))}
  },

  brights = {
${hexList(f.ansi.slice(8, 16))}
  },

  tab_bar = {
    background = ${quote(s.alt)},
    inactive_tab_edge = ${quote(s.alt)},

    active_tab = {
      bg_color = ${quote(tabActiveBg)},
      fg_color = ${quote(t.primary)},
      intensity = 'Bold',
      underline = 'None',
      italic = false,
      strikethrough = false,
    },

    inactive_tab = {
      bg_color = ${quote(s.alt)},
      fg_color = ${quote(tabFg)},
      intensity = 'Normal',
    },

    inactive_tab_hover = {
      bg_color = ${quote(hoverBg)},
      fg_color = ${quote(t.primary)},
      italic = false,
    },

    new_tab = {
      bg_color = ${quote(s.alt)},
      fg_color = ${quote(tabFg)},
    },

    new_tab_hover = {
      bg_color = ${quote(hoverBg)},
      fg_color = ${quote(t.primary)},
    },
  },

}
`;
}

export function generateKaku(): GeneratedFile[] {
  return flavors.map((flavor) => ({
    path: `dist/kaku/${kakuFileName(flavor)}`,
    content: buildKakuScheme(flavor),
  }));
}

/**
 * The same palette as a WezTerm-compatible TOML color scheme.
 *
 * Kaku reads `<config-dir>/colors/*.toml` and lists each file by its
 * `[metadata].name` in Settings → Theme, so the file has to carry the full
 * palette the Lua table does.
 */
export function buildKakuTomlScheme(flavor: Flavor): string {
  const f = flavor;
  const s = f.surface;
  const t = f.text;
  const y = f.syntax;
  const dark = f.meta.appearance === 'dark';
  const tabFg = t.secondary;
  const hoverBg = s.overlay;
  const zh = flavorName(f, 'zh');
  const en = flavorName(f, 'en');
  const name = kakuSchemeName(f);

  return `# 墨观 Inkstone · ${zh} · ${en}
# ${f.meta.description.en}
# Generated by \`pnpm build\` — do not edit by hand.
#
# Install: copy this file to ~/.config/kaku/colors/ (or ~/.config/wezterm/colors/),
# then pick "${name}" in Settings (Cmd+,) or set:
#
#   config.color_scheme = "${name}"

[colors]
foreground = ${tomlString(t.primary)}
background = ${tomlString(s.base)}
cursor_bg = ${tomlString(t.cursor)}
cursor_fg = ${tomlString(s.base)}
cursor_border = ${tomlString(t.cursor)}
selection_bg = ${tomlString(s.selection)}
selection_fg = ${tomlString(t.primary)}
compose_cursor = ${tomlString(y.number)}
scrollbar_thumb = ${tomlString(rgba(t.primary, dark ? 0.18 : 0.22))}
split = ${tomlString(s.overlay)}
visual_bell = ${tomlString(y.number)}
ansi = ${tomlArray(f.ansi.slice(0, 8))}
brights = ${tomlArray(f.ansi.slice(8, 16))}

[colors.tab_bar]
background = ${tomlString(s.alt)}
inactive_tab_edge = ${tomlString(s.alt)}

[colors.tab_bar.active_tab]
bg_color = ${tomlString(s.active)}
fg_color = ${tomlString(t.primary)}
intensity = "Bold"
underline = "None"
italic = false
strikethrough = false

[colors.tab_bar.inactive_tab]
bg_color = ${tomlString(s.alt)}
fg_color = ${tomlString(tabFg)}
intensity = "Normal"

[colors.tab_bar.inactive_tab_hover]
bg_color = ${tomlString(hoverBg)}
fg_color = ${tomlString(t.primary)}
italic = false

[colors.tab_bar.new_tab]
bg_color = ${tomlString(s.alt)}
fg_color = ${tomlString(tabFg)}

[colors.tab_bar.new_tab_hover]
bg_color = ${tomlString(hoverBg)}
fg_color = ${tomlString(t.primary)}

[metadata]
name = ${tomlString(name)}
`;
}

export function generateKakuToml(): GeneratedFile[] {
  return flavors.map((flavor) => ({
    path: `dist/kaku/${kakuTomlFileName(flavor)}`,
    content: buildKakuTomlScheme(flavor),
  }));
}
