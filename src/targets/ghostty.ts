/**
 * Ghostty themes.
 *
 * Ghostty theme files are plain config files. Installed into
 * ~/.config/ghostty/themes/, they can be selected with
 *   theme = light:Inkstone Xuanzhi,dark:Inkstone Xuanmo
 */

import { flavors } from '../palette/index.ts';
import type { Flavor } from '../palette/types.ts';
import { ANSI_NAMES } from '../palette/types.ts';
import type { GeneratedFile } from './vscode.ts';

export function buildGhosttyTheme(flavor: Flavor): string {
  const f = flavor;
  const lines = [
    `# 墨观 Inkstone · ${f.meta.zh} ${f.meta.en}`,
    `# ${f.meta.description.en}`,
    '# Generated by `pnpm build` — do not edit by hand.',
    '# Palette: zhongguose.com / 526 traditional Chinese colors',
    '',
    `background = ${f.surface.base}`,
    `foreground = ${f.text.primary}`,
    `cursor-color = ${f.syntax.keyword}`,
    `cursor-text = ${f.surface.base}`,
    `selection-background = ${f.surface.selection}`,
    `selection-foreground = ${f.text.primary}`,
    '',
  ];

  f.ansi.forEach((hex, index) => {
    lines.push(`palette = ${index}=${hex}`);
  });

  lines.push(
    '',
    '# ANSI reference:',
    ...f.ansi.map((hex, index) => `#   ${String(index).padStart(2, ' ')}  ${ANSI_NAMES[index]!.padEnd(14)} ${hex}`),
    '',
  );

  return lines.join('\n');
}

export function generateGhostty(): GeneratedFile[] {
  return flavors.map((flavor) => ({
    path: `dist/ghostty/Inkstone ${flavor.meta.en}`,
    content: buildGhosttyTheme(flavor),
  }));
}
