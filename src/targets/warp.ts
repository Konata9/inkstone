/**
 * Warp themes.
 *
 * Warp custom themes are small YAML files. Installed into ~/.warp/themes/
 * (macOS) or ${XDG_DATA_HOME:-~/.local/share}/warp-terminal/themes/ (Linux),
 * they show up in Settings → Appearance → Themes.
 *
 * Warp has no selection color, so the theme carries only the canvas, the
 * cursor, the UI accent and the 16 ANSI slots. The accent follows the
 * "red marks, blue acts" rule: Warp paints it on tabs, block selection and
 * focus, so it takes each flavor's action blue rather than the keyword red.
 */

import { flavors, flavorName } from '../palette/index.ts';
import type { Flavor } from '../palette/types.ts';
import { ANSI_NAMES } from '../palette/types.ts';
import { warpFileName, warpThemeName } from './naming.ts';
import type { GeneratedFile } from './vscode.ts';

/** Warp's eight color names, shared by the `normal` and `bright` groups. */
export const WARP_COLOR_NAMES = ANSI_NAMES.slice(0, 8);

/** YAML treats an unquoted `#` as a comment, so every value is quoted. */
function quote(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

export function buildWarpTheme(flavor: Flavor): string {
  const f = flavor;
  const zh = flavorName(f, 'zh');
  const en = flavorName(f, 'en');
  const group = (offset: number) =>
    WARP_COLOR_NAMES.map((name, index) => `    ${name}: ${quote(f.ansi[offset + index]!)}`);

  return [
    `# 墨观 Inkstone · ${zh} · ${en}`,
    `# ${f.meta.description.en}`,
    '# Generated by `pnpm build` — do not edit by hand.',
    '# Palette: zhongguose.com / 526 traditional Chinese colors',
    '',
    `name: ${quote(warpThemeName(f))}`,
    `accent: ${quote(f.action)}`,
    `cursor: ${quote(f.text.cursor)}`,
    `background: ${quote(f.surface.base)}`,
    `foreground: ${quote(f.text.primary)}`,
    `details: ${f.meta.appearance === 'dark' ? 'darker' : 'lighter'}`,
    'terminal_colors:',
    '  normal:',
    ...group(0),
    '  bright:',
    ...group(8),
    '',
  ].join('\n');
}

export function generateWarp(): GeneratedFile[] {
  return flavors.map((flavor) => ({
    path: `dist/warp/${warpFileName(flavor)}`,
    content: buildWarpTheme(flavor),
  }));
}
