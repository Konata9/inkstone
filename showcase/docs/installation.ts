const VSCODE_THEMES = table(
  ['变体', '命令面板里的名称'],
  flavors.map((flavor) => [flavorName(flavor), `\`${themeDisplayName(flavor)}\``]),
);

const ZED_THEMES = table(
  ['变体', 'Zed 主题名称', '模式'],
  flavors.map((flavor) => [
    flavorName(flavor),
    `\`${themeDisplayName(flavor)}\``,
    flavor.meta.appearance === 'dark' ? '暗' : '亮',
  ]),
);

const GHOSTTY_THEMES = table(
  ['变体', 'Ghostty 主题名', '模式'],
  flavors.map((flavor) => [
    flavorName(flavor),
    `\`${inkstoneThemeName(flavor)}\``,
    flavor.meta.appearance === 'dark' ? '暗' : '亮',
  ]),
);

const KAKU_THEMES = table(
  ['变体', 'Settings → Theme 里的名称'],
  flavors.map((flavor) => [flavorName(flavor), `\`${inkstoneThemeName(flavor)}\``]),
);

const OPENCODE_THEMES = table(
  ['主题名', '变体', '模式'],
  flavors.map((flavor) => [
    `\`inkstone-${flavor.meta.id}\``,
    flavorName(flavor),
    flavor.meta.appearance === 'dark' ? '暗' : '亮',
  ]),
);

const DSH_PAIRS_TABLE = table(
  ['包', '明（Light）', '暗（Dark）'],
  DSH_PAIRS.map((pair) => {
    const resolved = resolvePair(pair);
    return [
      `\`${dshPackageName(pair.id)}\``,
      flavorName(resolved.light),
      flavorName(resolved.dark),
    ];
  }),
);

